function createIconComponent() {
  const IconComp = ({ name, size = 20, color = '#FFFFFF', style }: IconProps) => {
    const LucideIcon = ICON_MAP[name] || Activity;
    const flatStyle = flattenStyle(style);
    return (
      <span
        style={{
          display: 'inline-flex',
          alignItems: 'center',
          justifyContent: 'center',
          lineHeight: 0,
          flexShrink: 0,
          ...flatStyle,
        }}
      >
        <LucideIcon size={size} color={color} strokeWidth={2.2} />
      </span>
    );
  };
  IconComp.font = {};
  IconComp.glyphMap = {} as Record<string, number>;
  return IconComp;
}

export const Ionicons = createIconComponent();
