// ─── Pre-indexed Lookup Maps (Zero Per-Call Sorting) ─────────────────────────
const EXACT_LOOKUP = new Map<string, CanonicalExercise>();

for (const item of CANONICAL_EXERCISES) {
  EXACT_LOOKUP.set(item.id.toLowerCase(), item);
  EXACT_LOOKUP.set(item.nameEn.toLowerCase(), item);
  EXACT_LOOKUP.set(item.nameUk.toLowerCase(), item);
  for (const alias of item.aliases) {
    const key = alias.trim().toLowerCase();
    if (key && !EXACT_LOOKUP.has(key)) {
      EXACT_LOOKUP.set(key, item);
    }
  }
}

function normalizeLookupToken(raw?: string): string {
  return (raw || '')
    .trim()
    .toLowerCase()
    .replace(/['`ʼ’]/g, '’')
    .replace(/\s+/g, ' ');
}

/**
 * Finds the canonical exercise definition by ID, English name, Ukrainian name,
 * or Hevy/Strong equipment-suffixed alias. Returns `null` for unknown custom exercises.
 */
export function findCanonicalExercise(idOrName?: string): CanonicalExercise | null {
  const norm = normalizeLookupToken(idOrName);
  if (!norm) return null;

  const direct = EXACT_LOOKUP.get(norm);
  if (direct) return direct;

  // Strip common CSV parenthetical suffixes: e.g. "Bench Press (Barbell)" -> "bench press"
  if (norm.includes('(')) {
    const stripped = norm.replace(/\s*\([^)]*\)\s*/g, ' ').trim().replace(/\s+/g, ' ');
    const byStripped = EXACT_LOOKUP.get(stripped);
    if (byStripped) return byStripped;
  }

  return null;
}

/**
 * Resolves a stable exercise identity string across generators, pickers, CSV imports,
 * PR detection, progression history, and notes.
 * For custom exercises not in the canonical registry, returns the normalized lowercase name.
 */
export function resolveCanonicalExerciseId(idOrName?: string): string {
  const canonical = findCanonicalExercise(idOrName);
  if (canonical) return canonical.id;
  return normalizeLookupToken(idOrName);
}

/**
 * Safely compares two exercise references across history, program templates, and PRs.
 * Prioritizes canonical exercise name matching so positional IDs (e.g. `upper-a-1`)
 * never cross-contaminate swapped exercises.
 */
export function areExercisesEquivalent(
  a: { id?: string; exerciseId?: string; name?: string; exerciseName?: string } | null | undefined,
  b: { id?: string; exerciseId?: string; name?: string; exerciseName?: string } | null | undefined
): boolean {
  if (!a || !b) return false;
  const nameA = a.name || a.exerciseName || '';
  const nameB = b.name || b.exerciseName || '';

  if (nameA.trim() && nameB.trim()) {
    return resolveCanonicalExerciseId(nameA) === resolveCanonicalExerciseId(nameB);
  }

  const idA = a.id || a.exerciseId || '';
  const idB = b.id || b.exerciseId || '';
  if (!idA || !idB) return false;
  return resolveCanonicalExerciseId(idA) === resolveCanonicalExerciseId(idB);
}

/**
 * Determines exact volume load semantics for both canonical and custom exercises.
 */
export function getExerciseLoadType(name?: string, equipment?: EquipmentId): ExerciseLoadType {
  const canonical = findCanonicalExercise(name);
  if (canonical) {
    // Respect explicit equipment override if user customized equipment on an exercise
    if (equipment && equipment !== canonical.equipment) {
      if (equipment === 'bodyweight') return 'bodyweight';
      if (equipment === 'barbell') return 'bilateral_total';
    } else {
      return canonical.loadType;
    }
  }

  const lower = normalizeLookupToken(name);
  if (lower.includes('assisted') || lower.includes('гравітрон') || lower.includes('gravitron')) {
    return 'assisted';
  }
  if (equipment === 'bodyweight') {
    return 'bodyweight';
  }

  // Unilateral movements MUST NOT be double-counted per logged set
  const isUnilateral =
    lower.includes('single-arm') ||
    lower.includes('single arm') ||
    lower.includes('one-arm') ||
    lower.includes('one arm') ||
    lower.includes('single-leg') ||
    lower.includes('single leg') ||
    lower.includes('bulgarian') ||
    lower.includes('split squat') ||
    lower.includes('step-up') ||
    lower.includes('step up') ||
    lower.includes('cable lateral') ||
    lower.includes('однією рукою') ||
    lower.includes('однією ногою') ||
    lower.includes('болгарськ') ||
    lower.includes('зашагуван') ||
    lower.includes('відведення руки');

  if (isUnilateral) {
    return 'unilateral_per_side';
  }

  // Single-dumbbell two-hand movements (Goblet Squat, Pullover, Two-hand Overhead Extension)
  const isSingleSharedDumbbell =
    lower.includes('goblet') ||
    lower.includes('pullover') ||
    lower.includes('overhead triceps') ||
    lower.includes('overhead extension') ||
    lower.includes('hip thrust') ||
    lower.includes('кубков') ||
    lower.includes('пуловер') ||
    lower.includes('французький жим гантел') ||
    lower.includes('місток з гантел');

  if (isSingleSharedDumbbell) {
    return 'bilateral_total';
  }

  if (
    equipment === 'dumbbells' ||
    lower.includes('dumbbell') ||
    lower.includes('db ') ||
    lower.includes('гантел') ||
    lower.includes('hammer curl') ||
    lower.includes('молотки')
  ) {
    return 'bilateral_per_hand';
  }

  return 'bilateral_total';
}
