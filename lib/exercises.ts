import type { EquipmentId } from '@/lib/programGenerator';

export type ExerciseCategoryMuscle = 'Chest' | 'Back' | 'Legs' | 'Shoulders' | 'Arms' | 'Core';

/**
 * Defines how user-entered set weight maps to total mechanical volume:
 * - `bilateral_total`: user enters total load moved (barbell, machine stack, single goblet/pullover DB). Volume = weight × reps.
 * - `bilateral_per_hand`: two dumbbells/handles moved simultaneously while user enters 1-hand weight. Volume = weight × 2 × reps.
 * - `unilateral_per_side`: one limb works at a time; each logged set represents the set performed. Volume = weight × 1 × reps (never double-counted).
 * - `bodyweight`: bodyweight movement (0 kg external by default; if weighted belt > 0 kg, Volume = weight × reps).
 * - `assisted`: counterweight machine (Gravitron) where higher weight = more assistance.
 */
export type ExerciseLoadType =
  | 'bilateral_total'
  | 'bilateral_per_hand'
  | 'unilateral_per_side'
  | 'bodyweight'
  | 'assisted';

